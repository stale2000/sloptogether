BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='sloptogether_app') THEN
    CREATE ROLE sloptogether_app NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
  END IF;
END;
$$;

GRANT USAGE ON SCHEMA sloptogether TO sloptogether_app;
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA sloptogether TO sloptogether_app;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA sloptogether TO sloptogether_app;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA sloptogether
  GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO sloptogether_app;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA sloptogether
  GRANT USAGE,SELECT ON SEQUENCES TO sloptogether_app;

COMMIT;
